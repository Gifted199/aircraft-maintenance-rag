"""The UI's look, in one place: U.S. Web Design System (USWDS) colour tokens, type and components.

The page follows the USWDS visual language (colours, Public Sans, 4px-radius buttons, left-border
alerts) so it sits comfortably next to aviation-authority websites. It deliberately uses no
agency's name, logo, seal, "official website" banner or .gov wording: it looks aligned with the
design system without pretending to be an official site.

Two outputs, both built from TOKENS so they cannot drift apart:
  * config_toml(): Streamlit's own theme (colours, font, radius), saved as ui/.streamlit/config.toml
    next to app.py, where Streamlit reads it whatever the working directory is. Regenerate with
    `python ui/theme.py`; a test fails if the file is out of date.
  * page_css(), header_html(), footer_html(): what Streamlit's theme cannot express (USWDS alert
    borders, focus outline, header bar, footer). Fixed text only: no model output goes through here.

Accessibility: every text/background pair is WCAG AA (4.5:1 or more; a test checks), focus is a
visible 4px outline, and every icon has text next to it.
"""

